/*
 * 강사 지도안 — 08번 문서 §2. 이 제품의 본체다.
 *
 * italki 는 교재를 주지 않는다. 강사는 차시당 1~2시간을 준비에 쓴다.
 * 그 시간을 0 으로 만드는 것이 상품이고, 기준은 하나다:
 *
 *   "첫 멘트부터 마무리 멘트까지 그대로 읽으면 되는 수준으로 작성.
 *    강사가 판단할 여지를 남기지 않는다."
 *
 * 그래서 지도안은 요약이 아니라 대본이다.
 * "핵심 표현을 도입한다" 같은 문장은 지도안이 아니다. 무엇을 말할지 적어야 한다.
 */

/** 50분 고정 틀 — 08번 문서 §2. 차시마다 바뀌지 않는다. */
