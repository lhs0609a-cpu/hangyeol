/*
 * K-pop 트랙 1~10차시 — 14번 문서 §2.5 의 1순위 트랙.
 *
 * 이 파일이 기존 curriculum.ts 와 다른 점.
 *
 * curriculum.ts 는 공통 뼈대다. 이 파일은 그 위에 얹는 첫 번째 트랙이고,
 * 어휘만 바꾼 것이 아니라 **말투와 순서까지 바꿨다.** 이유는 아래에 있다.
 *
 * ── 왜 반말이 먼저인가 ──────────────────────────────────
 *
 * 가사는 거의 전부 반말이다. 「보고 싶어」 「할 거야」 「좋아」.
 * 그런데 표준 커리큘럼은 해요체를 먼저 가르치고 반말을 30차시에 둔다.
 * K-pop 때문에 온 학습자는 29차시 동안 자기가 듣는 말을 못 만난다.
 *
 * ── 그런데 반말을 먼저 가르치면 위험하다 ────────────────
 *
 * 외국인이 반말을 먼저 익히면 사람에게 그대로 쓴다. 그건 무례가 된다.
 * Brown(2010, 2013)이 지적한 것이 정확히 이 문제다 — 교재의 경어 체계가
 * "foreigner talk" 에 기반해 실제 사용과 어긋나 있다.
 *
 * 그래서 수용과 산출을 갈랐다. 이 트랙의 핵심 설계다.
 *
 *   듣기 · 읽기(수용)  →  반말    가사가 반말이니까
 *   말하기(산출)       →  해요체  사람에게 쓸 것이니까
 *
 * 학습자에게 이 구분을 첫 시간에 명시적으로 알려 준다.
 * "노래는 반말이다. 사람한테는 해요체를 쓴다" 를 모르면
 * 첫 한국인 대화에서 사고가 난다.
 *
 * ── 노래를 어디에 쓰고 어디에 안 쓰는가 ─────────────────
 *
 * 근거가 갈린다. 14번 §3 에 원장이 있고 요약하면 이렇다.
 *
 *   발음 · 억양   노래 O   Baills et al.(2021) n=108, 억양 유의 개선
 *   어휘         노래 O   Murphy Odo(2022) 메타분석 27편·1,864명, 큰 효과
 *   문법         노래 X   통제된 효과크기 연구를 못 찾음
 *   자모(문자)   노래 X   del Egido(2023) 반증 — 음악훈련이 문자지식에 무영향
 *
 * 그래서 2~4차시(한글)에서 노래는 동기와 맥락만 준다.
 * 자모 자체는 명시적 문자 교육으로 가르친다. 아이돌 이름을 읽는 것은
 * 노래로 외우게 하는 것이 아니라 배운 자모를 즉시 써먹게 하는 것이다.
 *
 * ── 가사를 인쇄하지 않는다 ──────────────────────────────
 *
 * 가사는 작사가의 저작물이다. 교재에 전문을 실으면 라이선스가 필요하고,
 * KOMCA 요율을 확인하지 못했다(14번 §3).
 *
 * 대신 딕테이션으로 간다 — 교재에는 빈칸 틀만 있고 학습자가 음원을 들으며
 * 채운다. 인쇄물에 가사가 없으니 저작권 문제가 없고, 받아쓰기 자체가
 * 듣기 훈련이라 교육적으로도 낫다. 곡 제목과 아티스트명은 저작물이 아니다.
 *
 * ── 틀을 바꾸지 않는다 ──────────────────────────────────
 *
 * Rasti-Behbahani et al.(2026) 통제실험 n=70: 활동 형식이 산만할수록
 * 외재적 인지부하가 늘어 어휘 학습을 방해한다. "다양성이 곧 좋다"는 근거가 없다.
 *
 * 그래서 열 차시가 전부 같은 다섯 블록을 쓴다. 바뀌는 것은 소재뿐이다.
 */

/** K-pop 트랙 차시. 공통 뼈대에 트랙 고유 항목을 더한 것이다. */
export interface KpopUnit extends CurriculumUnitDraft {
  /**
   * 이 차시에서 학습자가 스스로 해내는 짧은 성공.
   *
   * 초반 이탈이 가장 큰 위험이고(언어앱 8주 26.3%), 자기효능감의 첫 원천은
   * 직접적 숙달 경험이다. 그래서 모든 차시에 하나씩 박아 둔다.
   * "배웠다" 가 아니라 "해냈다" 여야 한다.
   */
  firstWin: string;
  /** K-pop 과 어떻게 이어지는가. 곡 제목·아티스트명만 쓴다(가사 아님). */
  hook: string;
  /** 이 차시의 말투. 수용은 반말, 산출은 해요체로 갈린다. */
  register: 'receptive-반말' | 'productive-해요체' | 'both';
  /** 강사가 놓치기 쉬운 것. 지도안에 그대로 들어간다. */
  pitfall: string;
  /*
   * 1차시 전용 — 언어의 지도.
   *
   * 처음에 이것들을 targetForms 에 넣었더니 검사가 잡았다.
   * 「어순 SOV」 「조사가 있다」 는 습득할 문형이 아니라 언어의 특징이다.
   * 문형 칸에 넣으면 "차시당 문법 하나" 규칙이 거짓으로 깨진 것처럼 보이고,
   * 검사에 예외를 파면 그 예외로 다음 사람이 두 개씩 넣는다.
   * 그래서 칸을 따로 만들었다 — 1차시의 targetForms 는 비어 있는 것이 맞다.
   */
  orientationPoints?: readonly string[];
}

